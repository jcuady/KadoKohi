function p(
  id: string,
  categoryId: string,
  name: string,
  basePrice: number,
  temperature: ProductTemperature,
  order: number,
  opts?: { tags?: string[]; milks?: MilkOption[]; description?: string },
): Product {
  return {
    id,
    categoryId,
    branchId: null,
    name,
    description: opts?.description,
    basePrice,
    temperature,
    sizes: [],
    milks: opts?.milks ?? [],
    tags: opts?.tags,
    visible: true,
    order,
    createdAt: now(),
    updatedAt: now(),
  };
}

